"""Generate small RV32 FCVT vectors with an independent exact-rational oracle.

All256 exponent encodings, both signs, zero/max fractions, plus explicit
halfway and range/class boundaries. Five legal rounding modes and both
W/WU destinations. No host floating-point rounding or DUT helper calls.
Generated header/report belong below out/, not in the RTL source list.
"""
import argparse, hashlib, json
from fractions import Fraction
from pathlib import Path


def expected(bits, unsigned, rm):
    sign=bool(bits>>31); exponent=(bits>>23)&255; fraction=bits&0x7fffff
    lo,hi=(0,0xffffffff) if unsigned else (-0x80000000,0x7fffffff)
    if exponent==255:
        return ((hi if fraction or not sign else lo)&0xffffffff,16)
    mantissa=fraction if exponent==0 else (1<<23)|fraction
    power=-149 if exponent==0 else exponent-150
    value=Fraction(mantissa<<power,1) if power>=0 else Fraction(mantissa,1<<-power)
    q,remainder=divmod(value.numerator,value.denominator)
    den=value.denominator
    if rm==0: increment=2*remainder>den or (2*remainder==den and bool(q&1))
    elif rm==1: increment=False
    elif rm==2: increment=sign and bool(remainder)
    elif rm==3: increment=not sign and bool(remainder)
    elif rm==4: increment=2*remainder>=den
    else: raise ValueError('Unknown rounding mode')
    rounded=q+int(increment)
    if sign: rounded=-rounded
    if rounded<lo: return lo&0xffffffff,16
    if rounded>hi: return hi&0xffffffff,16
    return rounded&0xffffffff,int(bool(remainder))


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    assert not args.output.exists(), 'Preserve previous generated vectors'
    args.output.mkdir(parents=True)
    bits_set={sign<<31|exponent<<23|fraction
              for sign in (0,1) for exponent in range(256) for fraction in (0,0x7fffff)}
    for sign in (0,1):
        for exponent in (0,1,125,126,127,128,148,149,150,157,158,159,160,189,190,191,254,255):
            for fraction in (1,0x3fffff,0x400000,0x400001,0x7ffffe):
                bits_set.add(sign<<31|exponent<<23|fraction)
    vectors=sorted(bits_set)
    # Independent directed checks protect oracle ties/sign/invalid priority.
    checks=[(0x3f000000,False,0,(0,1)),(0xbf000000,False,0,(0,1)),
            (0x3fc00000,False,0,(2,1)),(0x40200000,False,0,(2,1)),
            (0xbf000000,True,1,(0,1)),(0xbf000000,True,2,(0,16)),
            (0xcf000000,False,0,(0x80000000,0)),
            (0x4f000000,False,0,(0x7fffffff,16)),
            (0x4f800000,True,0,(0xffffffff,16)),
            (0xff800001,False,0,(0x7fffffff,16))]
    for bits,unsigned,rm,wanted in checks:
        assert expected(bits,unsigned,rm)==wanted,(hex(bits),unsigned,rm)
    lines=['/* Generated by gen_vectors.py; exact rational expectations. */',
           'struct conversion_vector { unsigned bits; unsigned data[2][5]; unsigned char flags[2][5]; };',
           'static const struct conversion_vector conversion_vectors[] = {']
    for bits in vectors:
        rows=[[expected(bits,kind,rm) for rm in range(5)] for kind in (False,True)]
        data='{'+','.join('{'+','.join(f'0x{v:08x}u' for v,f in row)+'}' for row in rows)+'}'
        flags='{'+','.join('{'+','.join(str(f) for v,f in row)+'}' for row in rows)+'}'
        lines.append(f' {{0x{bits:08x}u,{data},{flags}}},')
    lines+=['};',f'#define CONVERSION_VECTOR_COUNT {len(vectors)}u','']
    header=args.output/'vectors.h';header.write_text('\n'.join(lines),encoding='utf-8')
    result=dict(scope=__doc__,vectors=len(vectors),staticConversions=len(vectors)*10,
                dynamicConversions=len(vectors)*2,totalConversions=len(vectors)*12,
                allExponentEncodings=256,signs=2,integerKinds=['W','WU'],roundingModes=5,
                oracleDirectedChecks=len(checks),
                generatorSha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest().upper(),
                headerSha256=hashlib.sha256(header.read_bytes()).hexdigest().upper())
    (args.output/'vectors.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
    print('Generated vectors',len(vectors),'conversions',len(vectors)*12,flush=True)


if __name__=='__main__':
    main()
