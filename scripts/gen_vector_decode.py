"""Generate strict RVV/Zvbb encoding classification from the recorded opcode tables.

This is an encoding decoder, not vector execution or a feature-completion claim.
The source snapshots are content bound; execute this script without network I/O.
"""
import hashlib,json,re
from sim_runner import ROOT,sha,dump
folder=ROOT/'config/vector_opcode_tables'
records=json.loads((folder/'sources.json').read_text())
entries=[]
for extension,record in zip(['V','ZVBB'],records,strict=True):
    path=ROOT/record['file'];assert sha(path)==record['sha256']
    for raw in path.read_text().splitlines():
        line=raw.split('#')[0].strip()
        if not line or line.startswith('$'):continue
        name,*tokens=line.split();mask=value=0;args=[]
        for token in tokens:
            if '=' not in token:args.append(token);continue
            bits,number=token.split('=');high,*rest=bits.split('..');hi=int(high);lo=int(rest[0]) if rest else hi
            field=((1<<(hi-lo+1))-1)<<lo;v=int(number,0)<<lo
            assert not mask&field and not v&~field,(name,token)
            mask|=field;value|=v
        enum='V_'+re.sub('[^A-Za-z0-9]','_',name).upper()
        entries.append({'name':name,'enum':enum,'mask':mask,'match':value,'arguments':args,'extension':extension})
assert len(entries)==391
for i,a in enumerate(entries):
    for b in entries[:i]:assert ((a['match']^b['match'])&(a['mask']&b['mask']))!=0,(a['name'],b['name'])
code=['// Generated by scripts/gen_vector_decode.py; encoding classification only.',
      '// Opcode data copyright (c) 2022 RISC-V International; BSD-3-Clause.',
      '// See config/vector_opcode_tables/LICENSE and sources.json.',
      'package rv_vector_decode_pkg;',
      '  typedef enum logic [8:0] { V_ILLEGAL=0,']
code += ['    '+e['enum']+(',' if i<len(entries)-1 else '') for i,e in enumerate(entries)]
integer_groups={}
for e in entries:
    if e['match']&127==0x57 and ((e['match']>>12)&7) in [0,2,3,4,6]:
        integer_groups.setdefault(e['name'].split('.')[0],[]).append(e['enum'])
code += ['  } vector_operation_e;', '  typedef enum logic [6:0] { VI_ILLEGAL=0,']
code += ['    VI_'+name.upper()+(',' if i<len(integer_groups)-1 else '') for i,name in enumerate(integer_groups)]
code += ['  } vector_integer_operation_e;',
    '  function automatic vector_integer_operation_e integer_operation(input vector_operation_e operation);',
    '    case(operation)']
for name,ops in integer_groups.items():
    code.append('      '+','.join(ops)+':return VI_'+name.upper()+';')
code += ['      default:return VI_ILLEGAL;','    endcase','  endfunction',
'''  typedef struct packed {
    logic valid,configuration,memory,store,fp_operation;
    logic [1:0] scalar_source_used,scalar_source_fp;
    logic scalar_destination,scalar_destination_fp;
    vector_operation_e operation;
  } vector_decode_t;
  function automatic vector_decode_t decode_vector(input logic [31:0] instruction,
                                                     input logic has_zvbb=1);
    vector_decode_t d;
    d='0;d.operation=V_ILLEGAL;
    casez(instruction)''']
for e in entries:
    args=e['arguments'];name=e['name'];op=e['match']&127;f3=(e['match']>>12)&7
    pattern=''.join(str((e['match']>>bit)&1) if (e['mask']>>bit)&1 else '?' for bit in range(31,-1,-1))
    fp=op==0x57 and f3 in [1,5]
    statements=[f'd.valid={"has_zvbb" if e["extension"]=="ZVBB" else "1"}',f'd.operation={e["enum"]}']
    if name.startswith('vset'):statements+=['d.configuration=1']
    if op in [7,0x27]:statements+=['d.memory=1']
    if op==0x27:statements+=['d.store=1']
    if fp:statements+=['d.fp_operation=1']
    if 'rs1' in args:statements+=['d.scalar_source_used[0]=1']
    if 'rs2' in args:statements+=['d.scalar_source_used[1]=1']
    if fp and 'rs1' in args:statements+=['d.scalar_source_fp[0]=1']
    if 'rd' in args:statements+=['d.scalar_destination=1']
    if name=='vfmv.f.s':statements+=['d.scalar_destination_fp=1']
    code.append(f"      32'b{pattern}:begin "+';'.join(statements)+';end')
code+=['      default:begin end','    endcase','    return d;','  endfunction','endpackage','']
path=ROOT/'rtl/backend/rv_vector_decode_pkg.sv';path.write_text('\n'.join(code))
dump(folder/'encodings.json',{'scope':'Encoding classification only; vector state and execution pending',
    'sources':records,'generator_sha256':sha(__file__),'rtl_sha256':sha(path),
    'integer_operations':list(integer_groups),'instructions':entries})
print('Generated vector decoder',len(entries),'distinct forms; execution remains pending')
